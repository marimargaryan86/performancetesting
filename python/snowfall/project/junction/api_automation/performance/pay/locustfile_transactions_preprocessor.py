import logging
import random
from argparse import ArgumentParser
from typing import ClassVar

from locust import HttpUser, events, task

logger = logging.getLogger()
logger.setLevel(logging.INFO)


@events.init_command_line_parser.add_listener  # type: ignore[misc]
def init_parser(parser: ArgumentParser) -> None:
    parser.add_argument(
        "--token",
        help="environment token to interact",
    )
    parser.add_argument(
        "--quotes",
        help="amount of quotes to produce",
    )
    parser.add_argument(
        "--payer-uuid",
        help="uuid of payer company",
    )
    parser.add_argument(
        "--beneficiary-uuid",
        help="uuid of beneficiary company",
    )


class Quotes(HttpUser):
    # example command for accounts with all currencies activated:
    # locust -f locustfile_preprocessor.py
    # --token $PAY_TOKEN --host https://api.pay.junction.dev -t 20s
    # --headless --autostart --quotes $QUOTES_AMOUNT
    # --payer-uuid e6cb9cbe-b81b-4fc0-83b5-2794a1eed179
    # --beneficiary-uuid dded3966-5c57-46dc-a8f8-212ae4287bde

    quotations_list: ClassVar[list[str]] = []

    @task
    def test_get_quotations(self) -> None:  # noqa: WPS210
        from_currency, to_currency = random.sample(get_expected_currencies_list(), 2)
        currency_pair = "{0}{1}".format(from_currency, to_currency)
        if currency_pair in get_disallowed_currency_pairs():
            from_currency = "USD"
            to_currency = "EUR"

        payload = {
            "data": {
                "type": "quotes",
                "attributes": {
                    "amount": 1000,
                    "externalReference": "pay quotation api perf tests",
                },
                "relationships": {
                    "fromCurrency": {
                        "data": {
                            "id": from_currency,
                            "type": "currencies",
                        },
                    },
                    "payer": {
                        "data": {
                            "id": self.environment.parsed_options.payer_uuid,
                            "type": "companies",
                        },
                    },
                    "beneficiary": {
                        "data": {
                            "id": self.environment.parsed_options.beneficiary_uuid,
                            "type": "companies",
                        },
                    },
                    "toCurrency": {
                        "data": {"id": to_currency, "type": "currencies"},
                    },
                },
            },
        }

        headers = {
            "Authorization": "Bearer {0}".format(self.environment.parsed_options.token),
            "Accept": "application/vnd.api+json",
            "Content-Type": "application/vnd.api+json",
        }
        response = self.client.post(
            url="/quotes",
            headers=headers,
            json=payload,
        )
        json_quotation_id = response.json()
        logger.info("response quotes : %s", response.json())
        quotation_id = json_quotation_id["data"]["id"]
        self.quotations_list.append(quotation_id)
        with open("quotations.txt", "a") as txt_file:
            txt_file.write(quotation_id)
            txt_file.write("\n")
        if len(self.quotations_list) >= int(self.environment.parsed_options.quotes):
            self.environment.runner.quit()


