import lagom
from lagom.integrations import starlette
from starlette import routing

from snowfall.project.junction.hub.service.hub_api.routes import (  # noqa: WPS235
    accounts,
    balances,
    beneficiaries,
    bills,
    companies,
    contacts,
    conversions,
    currencies,
    go_orders,
    refunds,
    transactions,
    users,
)
from snowfall.stdlib.integration.starlette import routes


def get_routes(dependencies: lagom.Container) -> list[routing.BaseRoute]:
    integration = starlette.StarletteIntegration(dependencies)
    user_handler = users.Users()

    return [
        routes.to_route(
            "/users",
            user_handler.list_,
            name="ListUsers",
        ),
        routes.to_route(
            "/users/{userId}",
            user_handler.view,
            name="ViewUser",
        ),
        integration.route(
            "/orders/{orderId}/bookings",
            go_orders.BookingsByOrder,
            name="ListBookingsByOrder",
        ),
        integration.route(
            "/cancellations/requests",
            go_orders.CancellationRequest,
            name="CreateCancellationRequest",
        ),
        integration.route(
            "/cancellations/requests/{cancellationRequestId}",
            go_orders.CancellationRequest,
            name="ViewCancellationRequest",
        ),
        integration.route(
            "/bookings/cancellations/{bookingCancellationId}",
            go_orders.BookingCancellation,
            name="UpdateBookingCancellationStatus",
        ),
        integration.route(
            "/bookings/{bookingId}",
            go_orders.Booking,
            name="ViewBooking",
        ),
        integration.route(
            "/bookings/{bookingId}/cancellation",
            go_orders.BookingsCancellationByBooking,
            name="ViewBookingCancellationByBooking",
        ),
        integration.route(
            "/bookings/{bookingId}/details",
            go_orders.DetailsByBooking,
            name="ListDetailsByBooking",
        ),
        integration.route(
            "/bookings/details/{bookingDetailsId}",
            go_orders.BookingDetails,
            name="ViewBookingDetails",
        ),
        integration.route(
            "/journeys/{journeyId}",
            go_orders.Journey,
            name="ViewJourney",
        ),
        integration.route(
            "/journeys",
            go_orders.Journeys,
            name="ListJourneys",
        ),
        integration.route(
            "/journeys/{journeyId}/orders",
            go_orders.OrdersByJourney,
            name="ListOrdersByJourney",
        ),
        integration.route(
            "/orders/{orderId}",
            go_orders.Order,
            name="ViewOrder",
        ),
        integration.route(
            "/accounts",
            accounts.Accounts,
            name="Accounts",
            methods=["GET", "POST"],
        ),
        integration.route(
            "/accounts/{accountId}",
            accounts.Account,
            name="Account",
            methods=["GET", "PATCH"],
        ),
        integration.route(
            "/companies",
            companies.AdminCompanies,
            name="Companies",
        ),
        integration.route(
            "/companies/accountless",
            companies.AdminAccountlessCompanies,
            name="AccountlessCompanies",
        ),
        integration.route(
            "/companies/{companyId}",
            companies.AdminCompany,
            name="Company",
            methods=["PATCH", "GET"],
        ),
        integration.route(
            "/companies/{companyId}/contacts",
            contacts.Contacts,
            name="Contact",
        ),
        integration.route(
            "/conversions/{conversionId}",
            conversions.Conversions,
            name="Conversion",
        ),
        integration.route(
            "/conversions",
            conversions.ListConversions,
            name="ListConversion",
            methods=["GET"],
        ),
        integration.route(
            "/beneficiaries",
            beneficiaries.Beneficiaries,
            name="Beneficiaries",
        ),
        integration.route(
            "/beneficiaries/{beneficiaryId}",
            beneficiaries.Beneficiary,
            name="Beneficiary",
            methods=["GET", "PATCH"],
        ),
        integration.route(
            "/accounts/{accountId}/balances",
            balances.Balances,
            name="Balances",
            methods=["GET"],
        ),
        integration.route(
            "/accounts/{accountId}/relationships/currencies",
            balances.Balances,
            name="Balances",
            methods=["POST"],
        ),
        integration.route(
            "/transactions",
            transactions.Transactions,
            name="Transactions",
            methods=["POST", "GET"],
        ),
        integration.route(
            "/transactions/{transactionId}",
            transactions.Transaction,
            name="Transactions",
            methods=["GET"],
        ),
        integration.route(
            "/bills",
            bills.Bills,
            name="Bills",
            methods=["GET"],
        ),
        integration.route(
            "/bills/{billId}",
            bills.Bill,
            name="Bills",
        ),
        integration.route(
            "/refunds",
            refunds.Refunds,
            name="Refunds",
        ),
        integration.route(
            "/refunds/{refundId}",
            refunds.Refund,
            name="Refund",
            methods=["PATCH", "GET"],
        ),
        integration.route(
            "/refunds/{refundId}/refund-position",
            refunds.RefundPosition,
            name="RefundPosition",
        ),
        integration.route(
            "/refunds/bookings/{bookingId}",
            refunds.RefundByBooking,
            name="RefundByBookingId",
        ),
        integration.route(
            "/currencies",
            currencies.ListCurrencies,
            name="Currencies",
        ),
        integration.route(
            "/currencies/{currencyId}",
            currencies.Currencies,
            name="Currencies",
        ),
    ]
