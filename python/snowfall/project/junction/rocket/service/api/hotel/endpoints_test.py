from typing import Any

import httpx
import pytest
from pytest_mock import MockerFixture

from snowfall.project.junction.rocket.service.api.hotel.repositories import (
    HotelSearchRepository,
)
from snowfall.vendor.junction_one.conftest import load_file_fixture
from snowfall.vendor.junction_one.models import autogenerated as j1


@pytest.fixture()
def example_request() -> Any:
    return {
        "data": {
            "type": "hotel-searches",
            "attributes": {
                "checkinAt": "2024-08-24T00:00:00Z",
                "checkoutAt": "2024-08-26T00:00:00Z",
                "latitude": 48.8533,
                "longitude": 2.34861,
                "radius": 20,
                "passengers": [{"dateOfBirth": "1980-02-03"}],
            },
        },
    }


async def test_hotel_search_creation(
    client: httpx.AsyncClient,
    mocker: MockerFixture,
    hotel_search_repo: HotelSearchRepository,
    example_request: Any,
) -> None:
    fixture = (await load_file_fixture("POST-v1-travel-hotel-searchHotels.json"))[
        "data"
    ]
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.search_hotels",
        return_value=j1.SearchHotelsResponse(**fixture),
    )

    response = await client.post("/hotel/searches", json=example_request)

    assert response.json() == {
        "id": mocker.mock_module.ANY,
        "attributes": {"status": "pending"},
    }
    assert response.status_code == 200

    found_result = await hotel_search_repo.find_by_id(response.json()["id"])
    assert found_result
    assert found_result.data[0].refs == fixture["hotels"][0]["refs"]


