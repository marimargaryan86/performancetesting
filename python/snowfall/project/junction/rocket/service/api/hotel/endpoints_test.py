async def test_hotel_search_creation(
    client: httpx.AsyncClient,
    mocker: MockerFixture,
    hotel_search_repo: HotelSearchRepository,
    example_request: Any,
) -> None:
    fixture = (await load_file_fixture("POST-v1-travel-hotel-searchHotels.json"))[
        "data"
    ]
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.search_hotels",
        return_value=j1.SearchHotelsResponse(**fixture),
    )

    response = await client.post("/hotel/searches", json=example_request)

    assert response.json() == {
        "data": {
            "id": mocker.mock_module.ANY,
            "type": "hotel-search",
            "attributes": {"status": "pending"},
        },
    }
    assert response.status_code == 200

    found_result = await hotel_search_repo.find_by_id(response.json()["data"]["id"])
    assert found_result
    assert found_result.data[0].refs == fixture["hotels"][0]["refs"]


