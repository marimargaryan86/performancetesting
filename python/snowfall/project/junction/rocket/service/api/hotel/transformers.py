from collections.abc import Mapping
from datetime import UTC, datetime
from typing import Any

from starlette import status

from snowfall.project.junction.rocket.service.api.air.models import Passenger
from snowfall.project.junction.rocket.service.api.common.date import (
    convert_datetime_to_date,
)
from snowfall.project.junction.rocket.service.api.common.passengers import (
    passengers_to_fake_user_ids,
)
from snowfall.project.junction.rocket.service.api.errors import RequestValidationError
from snowfall.project.junction.rocket.service.api.hotel import types
from snowfall.project.junction.rocket.service.api.hotel.models import (
    HotelSearchResult,
    Result,
)
from snowfall.stdlib import string
from snowfall.stdlib.integration.starlette import (
    models,
)
from snowfall.vendor.junction_one.models import autogenerated as j1


class HotelSearchResultTransformer(types.HotelSearchResultTransformer):
    def transform(self, value: j1.SearchHotelsResponse) -> HotelSearchResult:
        return HotelSearchResult(
            id=string.uuid(),
            data=[Result(**hotel.model_dump()) for hotel in value.hotels or []],
        )


class HotelSearchRequestTransformer(types.HotelSearchRequestTransformer):
    def transform(self, value: Mapping[str, Any]) -> j1.SearchHotelsRequest:
        attributes = value["data"]["attributes"]
        errors = []

        now = datetime.now(tz=UTC).date()

        passengers = [Passenger(**pa) for pa in attributes["passengers"]]

        request = j1.SearchHotelsRequest(
            checkin_date=convert_datetime_to_date(attributes["checkinAt"]),
            checkout_date=convert_datetime_to_date(attributes["checkoutAt"]),
            latitude=attributes["latitude"],
            longitude=attributes["longitude"],
            radius=attributes["radius"],
            user_ids=passengers_to_fake_user_ids(passengers),
        )

        for ii, passenger in enumerate(passengers):
            if passenger.date_of_birth > now:
                errors.append(
                    models.Error(
                        status=str(status.HTTP_422_UNPROCESSABLE_ENTITY),
                        code="invalid_birthday",
                        detail="birthday cannot be in the future",
                        source=models.ErrorSourcePointer(
                            pointer="/data/attributes/passengers/{0}/dateOfBirth".format(
                                ii,
                            ),
                        ),
                    ),
                )

        if request.checkin_date and request.checkin_date < now:
            errors.append(
                models.Error(
                    status=str(status.HTTP_422_UNPROCESSABLE_ENTITY),
                    code="invalid_checkin_date",
                    detail="checkin date cannot be in the past",
                    source=models.ErrorSourcePointer(
                        pointer="/data/attributes/checkinAt",
                    ),
                ),
            )

        if request.checkout_date and request.checkout_date < now:
            errors.append(
                models.Error(
                    status=str(status.HTTP_422_UNPROCESSABLE_ENTITY),
                    code="invalid_checkout_date",
                    detail="checkout date cannot be in the past",
                    source=models.ErrorSourcePointer(
                        pointer="/data/attributes/checkoutAt",
                    ),
                ),
            )

        if errors:
            raise RequestValidationError(errors)

        return request
