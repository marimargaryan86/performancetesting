from datetime import date

from pydantic import Field

from snowfall.project.junction.rocket.service.api.models import BaseModel
from snowfall.vendor.junction_one.models import autogenerated as j1


class Result(BaseModel):
    hotel: j1.Hotel | None = None
    checkin_date: date | None = None
    checkout_date: date | None = None
    currency: str | None = None
    total_price: float | None = None
    taxes_and_fees: float | None = None
    taxes_and_fees_per_night: float | None = None
    price_per_night: float | None = None
    flags: int | None = None
    distance: float | None = None
    rate_codes: list[str] | None = None
    refs: list[str] | None = None


class HotelSearchResult(BaseModel):
    id: str = Field(..., alias="_id")
    data: list[Result] = Field([])


class RoomsResult(BaseModel):
    room_type: str | None = None
    description: str | None = None
    bed_type: str | None = None
    currency: str | None = None
    total_price: float | None = None
    price_per_night: float | None = None
    taxes_and_fees: float | None = None
    taxes_and_fees_per_night: float | None = None
    checkin_time: j1.LocalTime | None = None
    checkout_time: j1.LocalTime | None = None
    cancellation: j1.HotelCancellation | None = None
    rate_code: j1.RoomRateCode | None = None
    rate_plan_type: j1.OtaRatePlanType | None = None
    perks: int | None = None
    flags: int | None = None
    ref: str | None = None
    room_id: str | None = None
    commission: float | None = None
    important: str | None = None
    hotel_pref_level: int | None = None
    hidden: bool | None = None
    in_policy: bool | None = None
    booking_blocked: bool | None = None
    approval_required: bool | None = None


class HotelRoomsSearchResult(BaseModel):
    id: str
    data: list[RoomsResult]
