from datetime import date

from pydantic import Field

from snowfall.project.junction.rocket.service.api.models import BaseModel
from snowfall.vendor.junction_one.models.autogenerated import Hotel


class Result(BaseModel):
    hotel: Hotel | None = None
    checkin_date: date | None = None
    checkout_date: date | None = None
    currency: str | None = None
    total_price: float | None = None
    taxes_and_fees: float | None = None
    taxes_and_fees_per_night: float | None = None
    price_per_night: float | None = None
    flags: int | None = None
    distance: float | None = None
    rate_codes: list[str] | None = None
    refs: list[str] | None = None


class HotelSearchResult(BaseModel):
    id: str = Field(..., alias="_id")
    data: list[Result] = Field([])
