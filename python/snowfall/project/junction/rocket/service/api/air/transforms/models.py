from snowfall.vendor.junction_one.models import autogenerated as j1
from snowfall.vendor.junction_one.models.autogenerated import AwareOrNaiveDatetime

# Overlay over j1client models, since according to j1 spec all fields are optional,
# while we want models that break and guarantee some fields exist before trying to
# execute any business logic above the data


class Airport(j1.Airport):
    timezone: str


class FareSegment(j1.FareSegment):
    segment_id: str
    cabin: str  # type: ignore[assignment]
    perks: int


class PricedFare(j1.PricedFare):
    currency: str
    price: float
    name: str
    segments: list[FareSegment]  # type: ignore[assignment]


class Offer(j1.Offer):
    od_id: str
    fares: dict[str, list[PricedFare]]  # type: ignore[assignment]


class Segment(j1.Segment):
    flight_number: str
    airline: str
    departure_station: str
    arrival_station: str
    departure_time: AwareOrNaiveDatetime
    arrival_time: AwareOrNaiveDatetime
    duration: int
    segment_key: str
    operating_airline: str | None


class OriginDestination(j1.OriginDestination):
    departure_station: str
    arrival_station: str
    departure_time: AwareOrNaiveDatetime
    arrival_time: AwareOrNaiveDatetime
    segments: list[str]


class SearchFlightsResponse(j1.SearchFlightsResponse):
    airports: dict[str, Airport]  # type: ignore[assignment]
    ods: dict[str, OriginDestination]  # type: ignore[assignment]
    offers: list[Offer]  # type: ignore[assignment]
    segments: dict[str, Segment]  # type: ignore[assignment]
