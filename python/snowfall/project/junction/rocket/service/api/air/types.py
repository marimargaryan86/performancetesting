from abc import ABC, abstractmethod

from snowfall.project.junction.rocket.service.api.air.models import (
    AirSearchRequest,
    AirSearchResult,
)
from snowfall.project.junction.rocket.service.places.v1alpha import places_pb2_grpc
from snowfall.vendor.junction_one.models import autogenerated as j1


class AirSearchResultTransformer(ABC):
    @abstractmethod
    def transform(
        self,
        value: j1.SearchFlightsResponse,
        search_id: str,
    ) -> list[AirSearchResult]:
        "Transform results from j1 into a list of Rocket AirSearchResults."


class AirSearchRequestTransformer(ABC):
    @abstractmethod
    async def transform_outbound_query(
        self,
        air_search_request: AirSearchRequest,
        places: places_pb2_grpc.PlacesServiceStub,
    ) -> j1.SearchFlightsRequest:
        "Transform search request to j1 outbound query."

    @abstractmethod
    async def transform_inbound_query(
        self,
        air_search_request: AirSearchRequest,
        outbound_flight_ref_id: str,
        places: places_pb2_grpc.PlacesServiceStub,
    ) -> j1.SearchFlightsRequest:
        "Transform search request to j1 inbound query."
