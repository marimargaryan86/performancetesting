from abc import ABC, abstractmethod
from collections.abc import Mapping
from typing import Any

from snowfall.project.junction.rocket.service.api.air.models import AirSearchResult
from snowfall.vendor.junction_one.models import autogenerated as j1


class AirSearchResultTransformer(ABC):
    @abstractmethod
    def transform(self, value: j1.SearchFlightsResponse) -> AirSearchResult:
        "Transform."


class AirSearchRequestTransformer(ABC):
    @abstractmethod
    def transform(self, value: Mapping[str, Any]) -> j1.SearchFlightsRequest:
        "Transform."


class AbstractAirSearchRepo(ABC):
    @abstractmethod
    async def insert(self, value: AirSearchResult) -> None:
        "Insert."

    @abstractmethod
    async def exists_id(self, search_id: str) -> bool:
        "ID exists."

    @abstractmethod
    async def find_by_id(self, id_: str) -> AirSearchResult:
        "Find by id."
