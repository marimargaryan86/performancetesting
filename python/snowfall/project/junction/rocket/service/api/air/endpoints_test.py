from typing import Any

import httpx
import pytest
from pytest_mock import MockerFixture

from snowfall.project.junction.rocket.service.api import fakes
from snowfall.project.junction.rocket.service.api.air.models import AirSearchResult
from snowfall.project.junction.rocket.service.api.air.repositories import AirSearchRepo
from snowfall.vendor.junction_one.models.autogenerated import (
    SearchFlightsResponse,
)


@pytest.fixture()
def example_request() -> Any:
    return {
        "data": {
            "type": "air-searches",
            "attributes": {
                "criteria": {
                    "origin": "PAR",
                    "destination": "LON",
                    "departureAt": "2024-03-24T00:00:00Z",
                },
                "passengers": [{"dateOfBirth": "1980-02-03"}],
            },
        },
    }


async def test_air_search_creation_and_storage(
    client: httpx.AsyncClient,
    mocker: MockerFixture,
    air_search_repo: AirSearchRepo,
    example_request: Any,
) -> None:
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.search_flights",
        return_value=SearchFlightsResponse(),
    )

    response = await client.post("/air/searches", json=example_request)

    assert response.status_code == 200
    assert response.json() == {
        "id": mocker.mock_module.ANY,
        "attributes": {
            "status": "pending",
        },
    }

    result_id = response.json()["id"]
    found_result = await air_search_repo.find_by_id(result_id)
    assert found_result.id == result_id


async def test_air_search_get_status(
    client: httpx.AsyncClient,
    mocker: MockerFixture,
    example_request: Any,
) -> None:
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.search_flights",
        return_value=SearchFlightsResponse(),
    )
    await client.post("/air/searches", json=example_request)

    response = await client.get("/air/searches/{0}".format(fakes.AIR_RESULT_UUID))

    assert response.status_code == 200
    assert response.json()["attributes"]["status"] == "completed"


async def test_air_search_retrieval(
    client: httpx.AsyncClient,
    air_search_repo: AirSearchRepo,
) -> None:
    uuid = "c7384289-a633-4bb3-83c6-3aafcb20a4ad"
    result = AirSearchResult(id=uuid, data=[])
    await air_search_repo.insert(result)
    response = await client.get(
        "/air/searches/{0}/results".format(uuid),
    )

    assert response.json()["id"] == uuid
    assert response.status_code == 200
