RESULT_UUID = "a26bc204-61a4-405a-bf68-abdf8084cbb5"


class FakeAirSearchResultTransformer(AirSearchResultTransformer):
    def transform(self, value: BaseModel) -> AirSearchResult:
        return AirSearchResult(id=RESULT_UUID, data=[])


class FakeAirSearchRequestTransformer(AirSearchRequestTransformer):
    def transform(self, value: Mapping[str, Any]) -> SearchFlightsRequest:
        return SearchFlightsRequest()


class FakeAirSearchRepo(AbstractAirSearchRepo):
    def __init__(self) -> None:
        self.inserted: list[AirSearchResult] = []

    async def insert(self, value: AirSearchResult) -> None:
        self.inserted.append(value)

    async def exists_id(self, search_id: str) -> bool:
        return search_id in {result.id for result in self.inserted}

    async def find_by_id(self, id_: str) -> AirSearchResult:
        assert len(self.inserted) == 1
        return self.inserted[0]


@pytest.fixture()
def air_search_repo() -> FakeAirSearchRepo:
    return FakeAirSearchRepo()


@pytest.fixture()
def air_app(
    junction_one_client: JunctionOneClient,
    air_search_repo: FakeAirSearchRepo,
) -> applications.Starlette:
    container = lagom.Container()
    container[JunctionOneClient] = junction_one_client
    container[AbstractAirSearchRepo] = air_search_repo  # type: ignore[type-abstract]
    container[AirSearchRequestTransformer] = FakeAirSearchRequestTransformer  # type: ignore[type-abstract]
    container[AirSearchResultTransformer] = FakeAirSearchResultTransformer  # type: ignore[type-abstract]

    integration = StarletteIntegration(container)

    route_list = [
        integration.route("/air/searches", routes.AirSearch, name="AirSearch"),
        integration.route(
            "/air/searches/{id}/results",
            routes.AirSearchRetrieval,
            name="AirSearchRetrieval",
        ),
        integration.route(
            "/air/searches/{id}",
            routes.AirSearchStatus,
            name="AirSearchStatus",
        ),
    ]

    return application.create_starlette_app(routes=route_list, openapi_path=None)


