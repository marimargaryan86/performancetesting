async def test_air_search_retrieval_includes(
    client: httpx.AsyncClient,
    air_search_request_repo: AirSearchRequestRepository,
    air_search_repo: AirSearchResultRepository,
    example_request: Any,
    example_air_search_result_one: Any,
) -> None:
    search_object = AirSearchRequestStorage(
        search_id=SEARCH_ID,
        reseller_id="RESELLER_ID",
        air=example_request["data"]["attributes"],
    )
    await air_search_request_repo.insert(search_object)

    await air_search_repo.insert(example_air_search_result_one)

    response = await client.get(
        "/air/searches/{0}/results?include=offers,resultDetails".format(SEARCH_ID),
    )

    assert response.json()["data"][0]["id"] == UUID
    assert response.status_code == 200

    includes = response.json().get("included")
    assert includes is not None

    for include in includes:
        assert include["type"] in {"air-offers", "air-result-details"}
