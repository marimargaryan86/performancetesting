class SearchCriteriaUnfulfilledError(Exception):
    """Search Criteria is missing values."""


class AirSearchRequestTransformer(types.AirSearchRequestTransformer):
    async def transform_outbound_query(
        self,
        air_search_request: rocket.AirSearchRequest,
        places_grpc: places_pb2_grpc.PlacesServiceStub,
    ) -> j1.SearchFlightsRequest:
        attributes = air_search_request.data.attributes
        destination = air_search_request.data.relationships.destination
        origin = air_search_request.data.relationships.origin

        (origin_airport, destination_airport) = await asyncio.gather(
            self._get_place_iata_by_id(
                places_grpc,
                origin.data.id,
            ),
            self._get_place_iata_by_id(
                places_grpc,
                destination.data.id,
            ),
        )

        return j1.SearchFlightsRequest(
            ods=[
                j1.OriginDestinationRequest(
                    arrival_airport=destination_airport,
                    departure_airport=origin_airport,
                    departure_date=attributes.departure_after.date(),
                ),
            ],
            user_ids=passengers_to_fake_user_ids(attributes.passengers),
        )

    async def transform_inbound_query(
        self,
        air_search_request: rocket.AirSearchRequest,
        outbound_flight_ref_id: str,
        places_grpc: places_pb2_grpc.PlacesServiceStub,
    ) -> j1.SearchFlightsRequest:
        attributes = air_search_request.data.attributes

        return_departure_at = attributes.return_at
        return_departure_after = (
            return_departure_at.date() if return_departure_at else None
        )
        if not return_departure_after:
            raise SearchCriteriaUnfulfilledError()

        destination = air_search_request.data.relationships.destination
        origin = air_search_request.data.relationships.origin

        (origin_airport, destination_airport) = await asyncio.gather(
            self._get_place_iata_by_id(
                places_grpc,
                origin.data.id,
            ),
            self._get_place_iata_by_id(
                places_grpc,
                destination.data.id,
            ),
        )
        return j1.SearchFlightsRequest(
            ods=[
                j1.OriginDestinationRequest(
                    arrival_airport=destination_airport,
                    departure_airport=origin_airport,
                    departure_date=attributes.departure_after.date(),
                ),
                j1.OriginDestinationRequest(
                    arrival_airport=origin_airport,
                    departure_airport=destination_airport,
                    departure_date=return_departure_after,
                ),
            ],
            user_ids=passengers_to_fake_user_ids(attributes.passengers),
            refs=[outbound_flight_ref_id],
        )

    async def _get_place_iata_by_id(
        self,
        places_grpc: places_pb2_grpc.PlacesServiceStub,
        place_id: str,
    ) -> str:
        place_response: places_pb2.GetPlaceResponse = await places_grpc.GetPlace(
            places_pb2.GetPlaceRequest(
                id=place_id,
            ),
        )
        search_capabilities = place_response.place.search_capabilities
        if search_capabilities.air:
            snowfall_id = next(iter(search_capabilities.air))
            return search_capabilities.air[snowfall_id]
        raise exceptions.HTTPException(
            status.HTTP_404_NOT_FOUND,
            "Cannot find place or place has no iata",
        )


def _transform_result_detail(
    segment: safej1.Segment,
    result_detail_id: str,
    origin_timezone: zoneinfo.ZoneInfo,
    destination_timezone: zoneinfo.ZoneInfo,
) -> rocket.ResultDetails:
    return rocket.ResultDetails(
        id=result_detail_id,
        flight_number=segment.flight_number,
        marketing_airline=segment.airline,
        arrival_station=segment.arrival_station,
        arrival_at=segment.arrival_time.replace(tzinfo=destination_timezone),
        departure_station=segment.departure_station,
        departure_at=segment.departure_time.replace(tzinfo=origin_timezone),
        duration=segment.duration,
        segment_key=segment.segment_key,
        operating_airline=segment.operating_airline or segment.airline,
    )


class AirSearchResultTransformer(types.AirSearchResultTransformer):
    def transform(
        self,
        j1_response: j1.SearchFlightsResponse,
        search_id: str,
    ) -> list[rocket.AirSearchResult]:
        safe_j1_response = safej1.SearchFlightsResponse(**j1_response.model_dump())
        offers = safe_j1_response.offers
        search_results = []
        for offer in offers:
            search_result = self._transform_search_result(
                offer,
                safe_j1_response,
                search_id,
            )
            search_results.append(search_result)

        return search_results

    def _transform_search_result(
        self,
        offer: safej1.Offer,
        j1_response: safej1.SearchFlightsResponse,
        search_id: str,
    ) -> rocket.AirSearchResult:
        result_details = []
        result_detail_id_from_segments = {}

        airport_timezones = {
            key: zoneinfo.ZoneInfo(airport.timezone)
            for key, airport in j1_response.airports.items()
        }
        full_trip = j1_response.ods[offer.od_id]
        for segment in full_trip.segments:
            result_detail_id = string.uuid()
            full_segment = j1_response.segments[segment]
            origin_timezone = airport_timezones[full_segment.departure_station]
            destination_timezone = airport_timezones[full_segment.arrival_station]
            result_detail = _transform_result_detail(
                full_segment,
                result_detail_id,
                origin_timezone,
                destination_timezone,
            )
            result_details.append(result_detail)
            result_detail_id_from_segments[segment] = result_detail_id

        offers = []
        for fare_type, priced_fares in offer.fares.items():
            for priced_fare in priced_fares:
                new_offer = rocket.Offer(
                    id=string.uuid(),
                    price=rocket.Price(
                        price=priced_fare.price,
                        currency=priced_fare.currency,
                    ),
                    cabin_details=(
                        self._transform_cabins(
                            priced_fare.segments,
                            result_detail_id_from_segments,
                        )
                    ),
                    fare_type=rocket.FareTypeEnum(fare_type),
                    name=priced_fare.name,
                    ref_ids=[ref for ref in priced_fare.refs if priced_fare.refs],
                )
                offers.append(new_offer)

        return rocket.AirSearchResult(
            id=string.uuid(),
            search_id=search_id,  # TODO(reuben.t): store the search in mongo
            provider_id=str(constants.JUNCTION_ONE_PROVIDER_ID),
            offers=offers,
            result_details=result_details,
        )

    def _transform_cabins(
        self,
        fare_segments: Sequence[safej1.FareSegment],
        result_detail_id_from_segments: Mapping[str, str],
    ) -> list[rocket.CabinDetails]:
        cabin_details = []
        for fare_segment in fare_segments:
            result_detail_id = result_detail_id_from_segments[fare_segment.segment_id]
            cabin = rocket.CabinDetails(
                id=string.uuid(),
                result_detail_id=result_detail_id,
                marketing_name=fare_segment.cabin or None,
            )
            cabin_details.append(cabin)

        return cabin_details
