from datetime import UTC, date, datetime, timedelta
from enum import Enum
from typing import Literal

from pydantic import Field

from snowfall.project.junction.rocket.service.api.models import BaseModel
from snowfall.vendor.junction_one.models.autogenerated import AwareOrNaiveDatetime


class StatusTypeEnum(Enum):
    """Status Types."""

    unspecified: str = "unspecified"
    pending: str = "pending"
    processing: str = "processing"
    completed: str = "completed"
    failed: str = "failed"


class FareTypeEnum(Enum):
    """Offer Fare Types."""

    basic: str = "1"
    standard: str = "2"
    enhanced: str = "3"
    premium: str = "4"
    premium_plus: str = "5"
    lux: str = "6"


class Passenger(BaseModel):
    date_of_birth: date


class AirSearchAttributes(BaseModel):
    departure_after: datetime
    origin: str
    destination: str
    return_departure_at: datetime | None = None
    passengers: list[Passenger]


class SelectedOutboundOfferData(BaseModel):
    id: str
    type: Literal["offers"]


class SelectedOutboundOffer(BaseModel):
    data: SelectedOutboundOfferData


class AirSearchRelationships(BaseModel):
    selected_outbound_offer: SelectedOutboundOffer


class AirSearchRequestData(BaseModel):
    type: Literal["air-searches"]
    attributes: AirSearchAttributes
    relationships: AirSearchRelationships | None = None


class AirSearchRequest(BaseModel):
    data: AirSearchRequestData


class SearchCapabilities(BaseModel):
    rail: bool
    air: bool
    ferry: bool


class ResultDetails(BaseModel):
    id: str = Field(..., alias="_id")
    flight_number: str
    airline: str
    arrival_station: str
    departure_station: str
    departure_at: AwareOrNaiveDatetime
    arrival_at: AwareOrNaiveDatetime
    duration: int = Field(..., alias="durationOfSegmentMinutes")
    segment_key: str
    operating_airline: str


class Price(BaseModel):
    price: float
    currency: str


class CabinDetails(BaseModel):
    id: str = Field(alias="uid")
    result_detail_id: str | None = Field(..., alias="resultDetailUid")
    marketing_name: str | None


class Offer(BaseModel):
    id: str = Field(..., alias="_id")
    price: Price
    fare_type: FareTypeEnum
    name: str
    cabin_details: list[CabinDetails] | None
    ref_ids: list[str]


class AirSearchResult(BaseModel):
    id: str = Field(..., alias="_id")
    search_id: str
    provider_id: str
    offers: list[Offer]
    result_details: list[ResultDetails]


def now_factory() -> datetime:
    return datetime.now(tz=UTC)


def expires_factory() -> datetime:
    return now_factory() + timedelta(hours=1)


class AirSearchRequestStorage(BaseModel):
    search_id: str
    reseller_id: str
    expires_at: datetime = Field(default_factory=expires_factory)
    created_at: datetime = Field(default_factory=now_factory)
    updated_at: datetime = Field(default_factory=now_factory)
    air: AirSearchAttributes


class AirSearchResponseAttributes(AirSearchAttributes):
    status: StatusTypeEnum
    expires_at: str
