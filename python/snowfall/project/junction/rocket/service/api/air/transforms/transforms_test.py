@freezegun.freeze_time("2024-03-20")
async def test_transform_basic_request(
    example_request_one_way: Any,
) -> None:
    search_request = AirSearchRequest(**example_request_one_way)
    transformed = AirSearchRequestTransformer().transform_outbound_query(search_request)
    assert transformed.model_dump(exclude_none=True) == {
        "ods": [
            {
                "arrival_airport": "LAX",
                "departure_airport": "JFK",
                "departure_date": date(2024, 1, 1),
            },
        ],
        "refs": [],
        "reservation_ids": [],
        "user_ids": [-10, -11, -21],
    }


@freezegun.freeze_time("2024-03-20")
async def test_transform_round_trip_request(
    example_request_round_trip: Any,
    example_air_search_result_with_offers: Any,
    air_search_repo: AirSearchResultRepository,
) -> None:
    await air_search_repo.insert(example_air_search_result_with_offers)

    result = await air_search_repo.find_result_by_offer_id(OUTBOUND_SEARCH_OFFER_ID)
    assert result is not None

    search_request = AirSearchRequest(**example_request_round_trip)
    transformed = AirSearchRequestTransformer().transform_inbound_query(
        search_request,
        "FLIGHT_REF_EXAMPLE",
    )
    assert isinstance(transformed, j1.SearchFlightsRequest)
    assert transformed.model_dump(exclude_none=True) == {
        "ods": [
            {
                "arrival_airport": "LAX",
                "departure_airport": "JFK",
                "departure_date": date(2024, 1, 1),
            },
            {
                "arrival_airport": "JFK",
                "departure_airport": "LAX",
                "departure_date": date(2024, 1, 2),
            },
        ],
        "refs": ["FLIGHT_REF_EXAMPLE"],
        "reservation_ids": [],
        "user_ids": [-10, -11],
    }


