class SearchError(Exception):
    """Base class for exceptions."""


class ValidationError(SearchError):
    """Base class for validation errors."""


class UnsupportedSegmentTypeError(ValidationError):
    """Raised when a route contains unsupported segment types."""


class UnsupportedRoundtripError(ValidationError):
    """Raised when the outbound and inbound routes does not match."""


class OfferNotFoundError(SearchError):
    """Raised when an offer is not found."""


class NoSuggestionError(SearchError):
    """Raised when there are no valid suggestions."""


class UnusableResponseError(SearchError):
    """Raised when a Junction One response is not usable."""


class ModeNotSupportedForResellerError(SearchError):
    def __init__(self, mode: segment_type_pb2.SegmentType.ValueType):
        super().__init__(
            "Mode '{0}' not supported for reseller.".format(
                protobuf.enum_value_to_slug(
                    segment_type_pb2.SegmentType.DESCRIPTOR,
                    mode,
                ),
            ),
        )


@dataclasses.dataclass(frozen=True, kw_only=True)
class Offer:
    id: str
    departure_at: datetime.datetime
    arrival_at: datetime.datetime
    type: segment_type_pb2.SegmentType.ValueType
    reference: str | None = None


@dataclasses.dataclass(frozen=True, kw_only=True)
class RoundtripOffer(Offer):
    outbound: Offer


OfferType = TypeVar("OfferType", bound=Offer)


@dataclasses.dataclass(frozen=True)
class Suggestion(Generic[OfferType]):
    offers: Sequence[OfferType]


@dataclasses.dataclass(frozen=True)
class Segment(Generic[OfferType]):
    segment: routes.Segment
    offers: Sequence[OfferType]

    def find_first_offer_after(
        self,
        earliest_departure: datetime.datetime,
    ) -> OfferType:
        for offer in self.offers:
            if offer.departure_at + self.segment.mct_prefix > earliest_departure:
                return offer

        raise OfferNotFoundError(
            "No offer found that departs after {departure_at}".format(
                departure_at=str(earliest_departure),
            ),
        )


@dataclasses.dataclass(frozen=True)
class SearchResult(Generic[OfferType]):
    route: routes.Route
    segments: list[Segment[OfferType]]
    departure_after: datetime.datetime

    def optimize(self) -> Suggestion[OfferType]:
        offers = []
        earliest_departure = self.departure_after

        for segment in self.segments:
            try:
                offer = segment.find_first_offer_after(earliest_departure)
            except OfferNotFoundError as err:
                raise NoSuggestionError("No valid suggestion available.") from err

            offers.append(offer)
            earliest_departure = offer.arrival_at + segment.segment.mct_suffix

        return Suggestion(offers=offers)


@dataclasses.dataclass(frozen=True)
class SegmentSearchRequest:
    segment: routes.Segment
    departure_after: datetime.datetime
    date_of_births: Sequence[datetime.date]
    reseller_id: str


OutboundSearchImplementation: TypeAlias = Callable[
    [SegmentSearchRequest],
    Awaitable[list[Offer]],
]
InboundSearchImplementation: TypeAlias = Callable[
    [Offer, SegmentSearchRequest],
    Awaitable[list[RoundtripOffer]],
]


class SearchImplementation(NamedTuple):
    mode: segment_type_pb2.SegmentType.ValueType
    outbound: OutboundSearchImplementation
    inbound: InboundSearchImplementation


class FlightSearcher:
    def __init__(
        self,
        client: j1_client.JunctionOneClient,
        j1_transformer: transforms.FlightSearchResultTransformer,
        repository: repositories.FlightSearchResultRepository,
        temp_auth: auth.TemporaryTokenAuth,
    ):
        self._logger = stdout.get_logger()
        self._client = client
        self._j1_transformer = j1_transformer
        self._repository = repository
        self._temp_auth = temp_auth

    async def outbound(self, request: SegmentSearchRequest) -> list[Offer]:
        with stdout.context_binding(
            origin=request.segment.origin.name,
            destination=request.segment.destination.name,
            departure_after=str(request.departure_after),
            reseller_id=request.reseller_id,
        ):
            response = await self._find_results(request)

        search_id = string.uuid()
        search_results = self._j1_transformer.transform(response, search_id)
        await asyncio.gather(*(self._repository.insert(doc) for doc in search_results))

        return list(
            itertools.chain.from_iterable([
                self._transform_outbound_result(result) for result in search_results
            ]),
        )

    async def inbound(
        self,
        outbound_offer: Offer,
        request: SegmentSearchRequest,
    ) -> list[RoundtripOffer]:
        with stdout.context_binding(
            origin=request.segment.origin.name,
            destination=request.segment.destination.name,
            departure_after=str(request.departure_after),
            reseller_id=request.reseller_id,
        ):
            response = await self._find_results(request, outbound_offer)

        search_id = string.uuid()
        search_results = self._j1_transformer.transform(response, search_id)
        await asyncio.gather(*(self._repository.insert(doc) for doc in search_results))

        return list(
            itertools.chain.from_iterable([
                self._transform_inbound_result(result, outbound_offer)
                for result in search_results
            ]),
        )

    async def _find_results(
        self,
        request: SegmentSearchRequest,
        outbound_offer: Offer | None = None,
    ) -> j1_models.SearchFlightsResponse:
        self._logger.info("Searching")

        with self._temp_auth.temporary(reseller_id=request.reseller_id):
            try:
                return await self._client.search_flights(
                    self._make_request(request, outbound_offer),
                )
            except ValueError as err:
                raise ModeNotSupportedForResellerError(request.segment.type) from err

    def _make_request(
        self,
        request: SegmentSearchRequest,
        outbound_offer: Offer | None = None,
    ) -> j1_models.SearchFlightsRequest:
        destination_capabilities = request.segment.destination.search_capabilities.air
        origin_capabilities = request.segment.origin.search_capabilities.air
        return j1_models.SearchFlightsRequest(
            ods=[
                j1_models.OriginDestinationRequest(
                    arrival_airport=destination_capabilities[IATA_PROVIDER_ID],
                    departure_airport=origin_capabilities[IATA_PROVIDER_ID],
                    departure_date=request.departure_after.date(),
                ),
            ],
            user_ids=passengers.passengers_to_fake_user_ids([
                models.Passenger(date_of_birth=date_of_birth)
                for date_of_birth in request.date_of_births
            ]),
            refs=[outbound_offer.reference]
            if outbound_offer and outbound_offer.reference
            else [],
        )

    def _transform_outbound_result(
        self,
        result: models.FlightSearchResult,
    ) -> list[Offer]:
        departure_at = result.result_details[0].departure_at
        arrival_at = result.result_details[-1].arrival_at

        return [
            Offer(
                id=offer.id,
                departure_at=departure_at,
                arrival_at=arrival_at,
                type=segment_type_pb2.SEGMENT_TYPE_FLIGHT,
                reference=offer.ref_ids[0],
            )
            for offer in result.offers
        ]

    def _transform_inbound_result(
        self,
        result: models.FlightSearchResult,
        outbound_offer: Offer,
    ) -> list[RoundtripOffer]:
        departure_at = result.result_details[0].departure_at
        arrival_at = result.result_details[-1].arrival_at

        return [
            RoundtripOffer(
                id=offer.id,
                departure_at=departure_at,
                arrival_at=arrival_at,
                type=segment_type_pb2.SEGMENT_TYPE_FLIGHT,
                reference=offer.ref_ids[0],
                outbound=outbound_offer,
            )
            for offer in result.offers
        ]


class RailSearcher:
    def __init__(
        self,
        searches: grpc_pb2_grpc.SearchServiceStub,
        search_results: grpc_pb2_grpc.SearchResultServiceStub,
        polling_interval: datetime.timedelta,
        search_window: datetime.timedelta,
    ):
        self._searches = searches
        self._search_results = search_results
        self._polling_interval = polling_interval
        self._search_window = search_window
        self._logger = stdout.get_logger()
        self._in_progress_statuses = {
            amqp_pb2.Trackable.STATUS_PENDING,
            amqp_pb2.Trackable.STATUS_PROCESSING,
        }

    async def outbound(self, request: SegmentSearchRequest) -> list[Offer]:
        with stdout.context_binding(
            origin=request.segment.origin.name,
            destination=request.segment.destination.name,
            departure_after=str(request.departure_after),
            reseller_id=request.reseller_id,
        ):
            search_results = await self._find_results(request)

        return list(
            itertools.chain.from_iterable([
                self._search_result_to_outbound_offers(search_result)
                for search_result in search_results
            ]),
        )

    async def inbound(
        self,
        outbound_offer: Offer,
        request: SegmentSearchRequest,
    ) -> list[RoundtripOffer]:
        with stdout.context_binding(
            origin=request.segment.origin.name,
            destination=request.segment.destination.name,
            departure_after=str(request.departure_after),
            reseller_id=request.reseller_id,
        ):
            search_results = await self._find_results(request, outbound_offer)

        return list(
            itertools.chain.from_iterable([
                self._search_result_to_inbound_offers(search_result, outbound_offer)
                for search_result in search_results
            ]),
        )

    def make_search_request(
        self,
        request: SegmentSearchRequest,
        outbound_offer: Offer | None = None,
    ) -> grpc_pb2.EnqueueSearchRequest:
        return grpc_pb2.EnqueueSearchRequest(
            search=searches_pb2.Search(
                reseller_id=request.reseller_id,
                rail=searches_pb2.Rail(
                    origin=request.segment.origin,
                    destination=request.segment.destination,
                    departure_after=protobuf.datetime_to_protobuf(
                        request.departure_after,
                    ),
                    departure_before=protobuf.datetime_to_protobuf(
                        request.departure_after + self._search_window,
                    ),
                    passengers=[
                        searches_pb2.Passenger(
                            date_of_birth=protobuf.date_to_protobuf(date_of_birth),
                        )
                        for date_of_birth in request.date_of_births
                    ],
                    outbound_offer_id=outbound_offer.id if outbound_offer else "",
                ),
            ),
        )

    def _search_result_to_outbound_offers(
        self,
        search_result: searches_pb2.SearchResult,
    ) -> list[Offer]:
        first_segment = min(
            search_result.result_details,
            key=lambda detail: detail.rail.segment_sequence,
        )
        last_segment = max(
            search_result.result_details,
            key=lambda detail: detail.rail.segment_sequence,
        )

        return [
            Offer(
                id=offer.id,
                departure_at=protobuf.protobuf_to_datetime(
                    first_segment.rail.departure_date,
                ),
                arrival_at=protobuf.protobuf_to_datetime(
                    last_segment.rail.arrival_date,
                ),
                type=segment_type_pb2.SEGMENT_TYPE_TRAIN,
            )
            for offer in search_result.offers
        ]

    def _search_result_to_inbound_offers(
        self,
        search_result: searches_pb2.SearchResult,
        outbound_offer: Offer,
    ) -> list[RoundtripOffer]:
        first_segment = min(
            search_result.result_details,
            key=lambda detail: detail.rail.segment_sequence,
        )
        last_segment = max(
            search_result.result_details,
            key=lambda detail: detail.rail.segment_sequence,
        )

        return [
            RoundtripOffer(
                id=offer.id,
                departure_at=protobuf.protobuf_to_datetime(
                    first_segment.rail.departure_date,
                ),
                arrival_at=protobuf.protobuf_to_datetime(
                    last_segment.rail.arrival_date,
                ),
                type=segment_type_pb2.SEGMENT_TYPE_TRAIN,
                outbound=outbound_offer,
            )
            for offer in search_result.offers
        ]

    async def _find_results(
        self,
        request: SegmentSearchRequest,
        outbound_offer: Offer | None = None,
    ) -> list[searches_pb2.SearchResult]:
        self._logger.info("Enqueuing search")
        response = await self._searches.EnqueueSearch(
            self.make_search_request(request, outbound_offer),
        )

        while response.search.status in self._in_progress_statuses:
            self._logger.info("Waiting for search to complete")
            await asyncio.sleep(self._polling_interval.total_seconds())
            response = await self._searches.GetSearch(
                grpc_pb2.GetSearchRequest(id=response.search.id),
            )

        result_response = await self._search_results.ListSearchResults(
            grpc_pb2.ListSearchResultsRequest(search_id=response.search.id),
        )
        self._logger.info(
            "Retrieved results",
            count=len(result_response.search_results),
        )

        return result_response.search_results


@dataclasses.dataclass(frozen=True)
class TripRequest:
    route: routes.Route
    departure_after: datetime.datetime


@dataclasses.dataclass(frozen=True)
class SearchRequest:
    outbound: TripRequest
    date_of_births: Sequence[datetime.date]
    reseller_id: str
    inbound: TripRequest | None = None

    def validate(self) -> None:
        self._validate_inbound_matches_outbound()

    def _validate_inbound_matches_outbound(self) -> None:
        if not self.inbound:
            return

        if len(self.outbound.route.segments) != len(self.inbound.route.segments):
            raise UnsupportedRoundtripError()

        segment_pairs = zip(
            self.outbound.route.segments,
            self.inbound.route.segments[::-1],
            strict=True,
        )

        for outbound, inbound in segment_pairs:
            if not outbound.is_inverse_of(inbound):
                raise UnsupportedRoundtripError()


class Searcher:
    def __init__(
        self,
        search_implementations: Iterable[SearchImplementation],
    ):
        self._outbound = {
            implementation.mode: implementation.outbound
            for implementation in search_implementations
        }
        self._inbound = {
            implementation.mode: implementation.inbound
            for implementation in search_implementations
        }
        self._supported_modes = {
            implementation.mode for implementation in search_implementations
        }

    async def find_results(
        self,
        request: SearchRequest,
    ) -> SearchResult[Offer] | SearchResult[RoundtripOffer]:
        self._validate_request(request)

        return await self._find_sequential(request)

    async def _find_sequential(
        self,
        request: SearchRequest,
    ) -> SearchResult[Offer] | SearchResult[RoundtripOffer]:
        outbound = await self._find_outbound_sequential(request)

        if not request.inbound:
            return outbound

        outbound_suggestion = outbound.optimize()
        outbound_offers = outbound_suggestion.offers[::-1]

        result_segments = []
        departure_after = request.inbound.departure_after

        for idx, segment in enumerate(request.inbound.route.segments):
            if idx > 0:
                departure_after += segment.mct_prefix

            offers = await self._inbound[segment.type](
                outbound_offers[idx],
                SegmentSearchRequest(
                    segment=segment,
                    departure_after=departure_after,
                    date_of_births=request.date_of_births,
                    reseller_id=request.reseller_id,
                ),
            )

            if not offers:
                raise OfferNotFoundError(
                    "No offers found for segment {origin}->{destination}".format(
                        origin=segment.origin.name,
                        destination=segment.destination.name,
                    ),
                )

            offers.sort(key=lambda offer: offer.arrival_at)
            result_segments.append(Segment(segment=segment, offers=offers))
            departure_after = offers[0].arrival_at + segment.mct_suffix

        return SearchResult(
            route=request.outbound.route,
            segments=result_segments,
            departure_after=departure_after,
        )

    async def _find_outbound_sequential(
        self,
        request: SearchRequest,
    ) -> SearchResult[Offer]:
        result_segments = []
        departure_after = request.outbound.departure_after

        for idx, segment in enumerate(request.outbound.route.segments):
            if idx > 0:
                departure_after += segment.mct_prefix

            offers = await self._outbound[segment.type](
                SegmentSearchRequest(
                    segment=segment,
                    departure_after=departure_after,
                    date_of_births=request.date_of_births,
                    reseller_id=request.reseller_id,
                ),
            )

            if not offers:
                raise OfferNotFoundError(
                    "No offers found for segment {origin}->{destination}".format(
                        origin=segment.origin.name,
                        destination=segment.destination.name,
                    ),
                )

            offers.sort(key=lambda offer: offer.arrival_at)
            result_segments.append(Segment(segment=segment, offers=offers))
            departure_after = offers[0].arrival_at + segment.mct_suffix

        return SearchResult(
            route=request.outbound.route,
            segments=result_segments,
            departure_after=request.outbound.departure_after,
        )

    def _validate_request(self, request: SearchRequest) -> None:
        self._validate_modes_are_supported(request)
        request.validate()

    def _validate_modes_are_supported(self, request: SearchRequest) -> None:
        if request.inbound:
            segments = request.outbound.route.segments + request.inbound.route.segments
        else:
            segments = request.outbound.route.segments

        for segment in segments:
            if segment.type not in self._supported_modes:
                raise UnsupportedSegmentTypeError(
                    "Segment type '{type}' not supported".format(
                        type=protobuf.enum_value_to_slug(
                            segment_type_pb2.SegmentType.DESCRIPTOR,
                            segment.type,
                        ),
                    ),
                )
