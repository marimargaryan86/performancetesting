def _is_inbound(
    flight_search_request: FlightSearchRequest,
) -> bool:
    return flight_search_request.data.relationships.selected_outbound_offer is not None


def _validate_request(search_request: FlightSearchRequest) -> None:
    if _is_inbound(search_request):
        relationships = search_request.data.relationships
        if relationships.selected_outbound_offer is None:
            raise exceptions.HTTPException(status.HTTP_400_BAD_REQUEST)


class FlightSearch(endpoints.HTTPEndpoint):
    @errors.handle_grpc_errors
    async def post(  # noqa: WPS217
        self,
        request: requests.Request,
        requests_repo: FlightSearchRequestRepository = lagom.injectable,
        search_task_producer: amqp.SearchTaskProducer = lagom.injectable,
    ) -> responses.Response:
        reseller_id = request.user.username
        request_data = await request.json()
        search_id = string.uuid()

        request_validator = SearchRequestValidator(request_data)
        if request_validator.validation_errors:
            return request_validator.as_json_api_response()

        search_request = FlightSearchRequest(**request_data)

        _validate_request(search_request)

        insert_response = await requests_repo.insert(
            FlightSearchRequestStorage(
                id=search_id,
                reseller_id=reseller_id,
                flight=request_data["data"]["attributes"],
            ),
        )

        await search_task_producer.publish(
            search_id=search_id,
            search_request_json=json.dumps(request_data),
            reseller_id=reseller_id,
            expires_at=insert_response.expires_at,
        )

        expires_at = insert_response.expires_at.isoformat()
        attributes_response = FlightSearchResponseAttributes(
            **request_data["data"]["attributes"],
            status=StatusTypeEnum.pending,
            expires_at=expires_at,
        ).model_dump(by_alias=True, exclude_none=True)

        response_model = models.Resource(
            id=search_id,
            type="flight-searches",
            attributes=attributes_response,
            links={
                "self": str(
                    request.url_for(
                        "FlightsSearch",
                    ),
                ),
            },
        )

        return await messages.create_response(
            body=models.Body(
                data=response_model,
            ),
            request=request,
            status_code=status.HTTP_201_CREATED,
        )


class FlightSearchStatus(endpoints.HTTPEndpoint):
    async def get(
        self,
        request: requests.Request,
        requests_repo: FlightSearchRequestRepository = lagom.injectable,
        results_repo: FlightSearchResultRepository = lagom.injectable,
    ) -> responses.Response:
        search_id: str = request.path_params["searchId"]

        search_result_from_requests_repo = await requests_repo.find_by_search_id(
            search_id,
        )

        if not search_result_from_requests_repo:
            raise exceptions.HTTPException(status.HTTP_404_NOT_FOUND)

        search_status = StatusTypeEnum.processing
        search_data = search_result_from_requests_repo.flight.model_dump(by_alias=True)
        expires_at = search_result_from_requests_repo.expires_at.isoformat()

        search_result_from_results_repo = (
            await results_repo.find_any_result_by_search_id(search_id)
        )
        if search_result_from_results_repo:
            search_status = StatusTypeEnum.completed

        attributes_response = FlightSearchResponseAttributes(
            **search_data,
            status=search_status,
            expires_at=expires_at,
        ).model_dump(by_alias=True, exclude_none=True)

        response_model = models.Resource(
            id=search_id,
            type="flight-searches",
            attributes=attributes_response,
            links={
                "self": str(
                    request.url_for(
                        "FlightsSearchStatus",
                        searchId=request.path_params["searchId"],
                    ),
                ),
            },
        )

        return await messages.create_response(
            body=models.Body(
                data=response_model,
            ),
            request=request,
            status_code=status.HTTP_200_OK,
        )


class FlightSearchRetrieval(endpoints.HTTPEndpoint):
    async def get(
        self,
        request: requests.Request,
        requests_repo: FlightSearchRequestRepository = lagom.injectable,
        results_repo: FlightSearchResultRepository = lagom.injectable,
    ) -> responses.Response:
        search_id = request.path_params["searchId"]
        search = await requests_repo.find_by_search_id(search_id)
        if not search:
            raise exceptions.HTTPException(status.HTTP_404_NOT_FOUND)

        result_set = await results_repo.find_results_by_search_id(search_id)

        response_data = [
            FlightSearchResultResource.from_model(
                search_result=search_result,
                search=search,
            )
            async for search_result in result_set
        ]

        pagination = pagination_helpers.get_pagination(request)
        items_page = sequence.paginate(
            sequence=response_data,
            cursor=pagination.cursor,
            limit=pagination.limit,
        )

        return await messages.create_response(
            body=models.Body(
                data=response_data,
                links=pagination_helpers.get_next_url(
                    request.url_for(
                        "FlightsSearchRetrieval",
                        searchId=request.path_params["searchId"],
                    ),
                    items_page.cursor,
                    pagination,
                ),
            ),
            request=request,
        )


class FlightOfferAddPassenger(endpoints.HTTPEndpoint):
    async def post(  # noqa: WPS217
        self,
        request: requests.Request,
        redis_client: redis.Client[bytes] = lagom.injectable,
        junction_one_client: JunctionOneClient = lagom.injectable,
        results_repo: FlightSearchResultRepository = lagom.injectable,
        trip_repo: RocketTripRepository = lagom.injectable,
    ) -> responses.Response:
        offer_id = request.path_params["offerId"]
        add_passenger_request = AddPassengerRequest(**(await request.json()))
        search_result = await results_repo.find_result_by_offer_id(offer_id)

        offer_requires_passport = search_result.offer_requires_passport(offer_id)
        passport_required = (
            offer_requires_passport
            and not add_passenger_request.data.attributes.document
        )
        if passport_required:
            raise exceptions.HTTPException(
                status.HTTP_400_BAD_REQUEST,
                detail="Passport data is required",
            )

        attrs = add_passenger_request.data.attributes
        reseller_user = await junction_one_client.create_reseller_user(
            auto_models.CreateUserAccountRequest(
                dob=attrs.dob,
                email=attrs.email,
                first_name=attrs.first_name,
                gender=attrs.gender,
                last_name=attrs.last_name,
                middle_name=attrs.middle_name,
                phone_number=attrs.phone_number,
                suffix=attrs.suffix,
            ),
        )

        if not reseller_user.id:
            raise ValueError(
                "Failed to create user: {0}".format(
                    add_passenger_request.data.attributes,
                ),
            )

        if offer_requires_passport:
            document = cast(
                Document,
                add_passenger_request.data.attributes.document,
            )
            await junction_one_client.update_passport(
                PassportUpdateRequest(
                    id=reseller_user.id,
                    country=document.document_issue_country,
                    expiry=document.document_expiration_date,
                    nationality=document.nationality,
                    number=document.document_number,
                ),
            )

        async with redis_client.lock("lock:offers:{0}:trip".format(offer_id)):
            passenger_ids = await self._add_passenger_to_trip(
                offer_id,
                reseller_user.id,
                search_result,
                junction_one_client,
                trip_repo,
            )

        self_url = request.url_for("FlightPassenger", passengerId=passenger_ids.id)

        return await messages.create_response(
            body=models.Body(
                data=models.Resource(
                    id=passenger_ids.id,
                    type="passengers",
                    links={"self": str(self_url)},
                    attributes={},
                ),
            ),
            request=request,
            status_code=status.HTTP_201_CREATED,
        )

    async def _add_passenger_to_trip(
        self,
        offer_id: str,
        reseller_user_id: int,
        search_result: FlightSearchResult,
        junction_one_client: JunctionOneClient = lagom.injectable,
        trip_repo: RocketTripRepository = lagom.injectable,
    ) -> PassengerIds:
        trip = await trip_repo.find_by_offer_id(offer_id)
        passenger_ids = PassengerIds(
            id=string.uuid(),
            reseller_user_id=reseller_user_id,
        )

        if trip:
            same_id = [
                pa
                for pa in trip.passenger_ids
                if pa.reseller_user_id == reseller_user_id
            ]
            if same_id:
                return same_id[0]

            trip.passenger_ids.append(passenger_ids)
        else:
            refs = search_result.get_ref_ids_for_offer(offer_id)
            trip_create_response = await junction_one_client.create_trip_with_refs(
                TripCreateRefsRequest(
                    name="Trip {0}".format(refs[0]),
                    flight_refs=",".join(map(str, refs)),
                ),
            )

            trip = RocketTrip(
                id=string.uuid(),
                provider_trip_id=_get_trip_id(trip_create_response),
                offer_id=offer_id,
                passenger_ids=[passenger_ids],
                reservation_ids=functools.reduce(
                    operator.iadd,
                    [
                        ref.reservation_ids
                        for board in trip_create_response.boards
                        for ref in board.refs
                    ],
                    [],
                ),
            )
        await trip_repo.upsert(trip)
        await asyncio.gather(
            *(
                junction_one_client.update_reservation(
                    UpdateReservationRequest(
                        id=id_,
                        user_ids=[pa.reseller_user_id for pa in trip.passenger_ids],
                    ),
                )
                for id_ in trip.reservation_ids
            ),
        )
        return passenger_ids


def _get_trip_id(get_boards_response: auto_models.GetTripBoardsResponse) -> int:
    if not get_boards_response.trip or not get_boards_response.trip.id:
        raise ValueError("Trip ID is missing")

    return get_boards_response.trip.id
