from collections.abc import Sequence
from datetime import UTC, date, datetime, timedelta

import pytest

from snowfall.vendor.junction_one.client import JunctionOneClient
from snowfall.vendor.junction_one.models import autogenerated as auto_models
from snowfall.vendor.junction_one.models import base as models


@pytest.mark.integration()
async def test_e2e_flights_flow(remote_junction_one_client: JunctionOneClient) -> None:  # noqa: WPS217,WPS218
    """Test end to end booking one way flight."""
    ####################################################################################
    # 1. Search for flights
    #
    # This is 3 endpoints in the api: create the flight, poll for the status, and get
    # the results
    ####################################################################################
    user_ids = [-10]
    org_id = 2623634
    search_req = auto_models.SearchFlightsRequest(
        refs=[],
        user_ids=user_ids,
        org_id=org_id,
        ods=[
            auto_models.OriginDestinationRequest(
                departure_airport="LON",
                arrival_airport="PAR",
                departure_date=datetime.now(tz=UTC).date() + timedelta(days=1),
            ),
        ],
    )

    search_flights_response = await remote_junction_one_client.search_flights(
        search_req,
    )

    # Get offer ref that is chosen to create the trip
    assert search_flights_response.offers
    offer = search_flights_response.offers[0]

    assert offer.fares
    fare = offer.fares["2"][0]
    flight_offer_ref = fare.refs

    assert flight_offer_ref
    assert search_req.ods
    destination_loc = search_req.ods[0].arrival_airport

    ####################################################################################
    # 2. Add a passenger
    #
    # This endpoint will do three things:
    #    - create the trip if it hasn't been created
    #    - create the reseller user
    #    - update all reservations to include the given users.
    #
    # It will take this form:
    #
    # POST "/air/offers/:offerId/passengers"
    # (The linter doesn't allow the inclusion of a sample JSON because it considers it
    # code. The example will live forever in our memory.)
    ####################################################################################
    new_user = await remote_junction_one_client.create_reseller_user(
        auto_models.CreateUserAccountRequest(
            email="email@example.com",
            first_name="John",
            middle_name="Middle",
            last_name="Smith",
            suffix="SR",
            dob=date(2000, 1, 1),
            gender=auto_models.Gender.male,
            phone_number="4407771000000",
            flags=0,
        ),
        org_id=org_id,
    )
    assert new_user.id

    # Create a trip
    trip_create_response = await remote_junction_one_client.create_trip_with_refs(
        models.TripCreateRefsRequest(
            name="Trip to {0}".format(destination_loc),
            flight_refs=flight_offer_ref[0],
        ),
    )

    assert trip_create_response.boards
    board = trip_create_response.boards[0]
    assert board.refs

    # Assert that the users are the anonymous ones.
    assert isinstance(board.summary, Sequence)
    assert board.summary[0].user_ids == user_ids

    tripboard_ref = board.refs[0]
    flight_reservations = tripboard_ref.reservation_ids
    assert flight_reservations

    reservation_id = flight_reservations[0]

    # Replace the users with the new reseller user.
    reservation = await remote_junction_one_client.update_reservation(
        models.UpdateReservationRequest(id=reservation_id, user_ids=[new_user.id]),
    )
    assert reservation.user_ids == [new_user.id]

    ####################################################################################
    # 3. (Optional) Get seatmaps
    ####################################################################################

    seatmaps = await remote_junction_one_client.get_seatmap_for_flights(
        auto_models.FlightSeatMapRequest(refs=flight_offer_ref),
    )

    first_segment_seatmap = seatmaps.segments[0]
    assert first_segment_seatmap.seat_types

    first_available_seat = next(
        seat
        for seat in first_segment_seatmap.seats()
        if seat.status == auto_models.SeatStatus.available
    )
    assert first_available_seat.seat_key

