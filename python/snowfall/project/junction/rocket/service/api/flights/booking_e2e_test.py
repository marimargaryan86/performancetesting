@pytest.mark.integration()
async def test_e2e_booking_flow(  # noqa: WPS217,WPS218
    pay_gw_client: PayGwClient,
    remote_junction_one_client: JunctionOneClient,
    remote_quotations_stub: transactions_pb2_grpc.QuotationsServiceStub,
    authorization: str,
    *,
    seatmap_flow: bool,
) -> None:
    """Test end to end booking one way flight."""
    ####################################################################################
    # 1. Search for flights
    #
    # This is 3 endpoints in the api: create the flight, poll for the status, and get
    # the results
    ####################################################################################
    user_ids = [-10]
    org_id = 2623634
    search_req = auto_models.SearchFlightsRequest(
        refs=[],
        user_ids=user_ids,
        org_id=org_id,
        ods=[
            auto_models.OriginDestinationRequest(
                departure_airport="LON",
                arrival_airport="PAR",
                departure_date=datetime.now(tz=UTC).date() + timedelta(days=1),
            ),
        ],
    )

    search_flights_response = await remote_junction_one_client.search_flights(
        search_req,
    )

    # Get offer ref that is chosen to create the trip
    assert search_flights_response.offers
    offer = search_flights_response.offers[0]

    assert offer.fares
    fare = offer.fares["2"][0]
    flight_offer_ref = fare.refs

    assert flight_offer_ref
    assert search_req.ods
    destination_loc = search_req.ods[0].arrival_airport

    ####################################################################################
    # 2. Add a passenger
    #
    # This endpoint will do three things:
    #    - create the trip if it hasn't been created
    #    - create the reseller user
    #    - update all reservations to include the given users.
    #
    # It will take this form:
    #
    # POST "/air/offers/:offerId/passengers"
    # (The linter doesn't allow the inclusion of a sample JSON because it considers it
    # code. The example will live forever in our memory.)
    ####################################################################################
    new_user = await remote_junction_one_client.create_reseller_user(
        auto_models.CreateUserAccountRequest(
            email="email@example.com",
            first_name="John",
            middle_name="Middle",
            last_name="Smith",
            suffix="SR",
            dob=date(2000, 1, 1),
            gender=auto_models.Gender.male,
            phone_number="4407771000000",
            flags=0,
        ),
        org_id=org_id,
    )
    assert new_user.id

    # Create a trip
    trip_boards_response = await remote_junction_one_client.create_trip_with_refs(
        models.TripCreateRefsRequest(
            name="Trip to {0}".format(destination_loc),
            flight_refs=flight_offer_ref[0],
        ),
    )

    assert trip_boards_response.boards
    board = trip_boards_response.boards[0]
    assert board.refs

    # Assert that the users are the anonymous ones.
    assert isinstance(board.summary, Sequence)
    assert board.summary[0].user_ids == user_ids

    tripboard_ref = board.refs[0]
    flight_reservations = tripboard_ref.reservation_ids
    assert flight_reservations

    reservation_id = flight_reservations[0]

    # Replace the users with the new reseller user.
    reservation = await remote_junction_one_client.update_reservation(
        models.UpdateReservationRequest(id=reservation_id, user_ids=[new_user.id]),
    )
    assert reservation.user_ids == [new_user.id]

    ####################################################################################
    # 3. (Optional) Get seatmaps
    ####################################################################################

    ####################################################################################
    # 4. (Optional) Assign seatmap to a user
    ####################################################################################

    if seatmap_flow:
        seatmaps = await remote_junction_one_client.get_seatmap_for_flights(
            auto_models.FlightSeatMapRequest(refs=flight_offer_ref),
        )

        first_segment_seatmap = seatmaps.segments[0]
        assert first_segment_seatmap.seat_types

        first_available_seat = next(
            seat
            for seat in first_segment_seatmap.seats()
            if seat.status == auto_models.SeatStatus.available
        )
        assert first_available_seat.seat_key

    ####################################################################################
    # 5. Reprice/Quote creation
    ####################################################################################

    assert trip_boards_response.trip
    assert trip_boards_response.trip.id
    assert board.id
    trip_boards_response = await _reprice_trip_board(
        remote_junction_one_client=remote_junction_one_client,
        trip_board_id=board.id,
        trip_id=trip_boards_response.trip.id,
    )
    await _create_pay_quote(
        remote_quotations_stub=remote_quotations_stub,
        price=_get_total_price(trip_boards_response),
    )

    ####################################################################################
    # 6. Get transaction token
    ####################################################################################

    transaction_token = await pay_gw_client.transaction_token(
        TransactionTokenAttributes(user_id=new_user.id, session_token=authorization),
    )

    ####################################################################################
    # 7. Add credit card (call to pay)
    ####################################################################################

    await pay_gw_client.credit_card(
        CreditCardAttributes(
            number="4242424242424242",
            cvc="443",
            expiration="11/2025",
            holder_name="Sargis Aghabekyan",
            is_default=True,
            billing_address=BillingAddress(
                country="US",
                country_code="US",
                state="AL",
                state_code="AL",
                city="Test",
                address1="123 Main Street",
                zip_code="22222",
            ),
        ),
        transaction_token,
    )

    ####################################################################################
    # 8. Book
    ####################################################################################

    ####################################################################################
    # 9. Poll until tripboard is processed.
    ####################################################################################


_SLEEP_SECONDS = 5
_CUT_OFF_SECONDS = 60


async def _reprice_trip_board(
    remote_junction_one_client: JunctionOneClient,
    trip_board_id: int,
    trip_id: int,
) -> auto_models.GetTripBoardsResponse:
    await remote_junction_one_client.process_tripboard(
        models.TripboardProcessRequest(
            id=trip_board_id,
            flag=auto_models.TripBoardProcessingFlags.reprice,
        ),
    )

    await asyncio.sleep(_SLEEP_SECONDS)

    async with asyncio.timeout(_CUT_OFF_SECONDS):
        while True:
            boards_response = await remote_junction_one_client.get_tripboards(
                trip_id=trip_id,
            )
            board = next(
                board_obj
                for board_obj in boards_response.boards
                if board_obj.id == trip_board_id
            )

            if board.processing_flags == 0:
                return boards_response

            if board.exception_flags:
                raise ValueError("Exception flags are set")

            await asyncio.sleep(_SLEEP_SECONDS)


async def _create_pay_quote(
    remote_quotations_stub: transactions_pb2_grpc.QuotationsServiceStub,
    price: money.Money,
) -> transaction_models_pb2.Quotation:
    quote_response = await remote_quotations_stub.CreateQuotation(
        request=transactions_pb2.CreateQuotationRequest(
            from_currency="USD",
            to_currency="USD",
            amount=price.amount,
            payer_id="6f1a9cff-a27e-4e93-b985-14d4283d36a0",
            beneficiary_id="da2bf234-8ea2-4304-941c-c01beff50da2",
            session_token="",
        ),
    )

    return quote_response.quotation


_DEFAULT_CURRENCY = "USD"


def _get_total_price(
    trip_boards_response: auto_models.GetTripBoardsResponse,
) -> money.Money:
    prices = [
        reservation.total_price
        for reservation in trip_boards_response.flight_reservations.values()
    ]

    price = money.from_string(str(prices[0]), money.Currency(_DEFAULT_CURRENCY))

    for idx in range(1, len(prices)):
        price = price.add(
            money.from_string(str(prices[idx]), money.Currency(_DEFAULT_CURRENCY)),
        )

    return price
