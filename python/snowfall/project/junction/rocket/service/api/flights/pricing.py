_DEFAULT_CURRENCY_CODE = "USD"


@dataclasses.dataclass(frozen=True)
class Repositories:
    quotes_repository: repositories.QuoteRepository
    trips_repository: repositories.RocketTripRepository


@dataclasses.dataclass(frozen=True)
class ProviderClient:
    junction_one_client: client.JunctionOneClient
    auth: j1_auth.TemporaryTokenAuth


def _get_price(
    get_boards_response: auto_models.GetTripBoardsResponse,
    board_ids: frozenset[int],
) -> money.Money:
    price = None
    boards_to_process = [
        board for board in get_boards_response.boards if board.id in board_ids
    ]

    for board in boards_to_process:
        for ref in board.refs:
            currency = money.Currency(ref.currency or _DEFAULT_CURRENCY_CODE)
            ref_price = money.from_string(str(ref.total), currency)

            price = ref_price if price is None else price.add(ref_price)  # type: ignore[redundant-expr, attr-defined]

    if not price:
        raise ValueError("No price found from boards")

    return price


class _PayQuoteCreationFailedError(Exception):
    """Raised when pay quote creation fails."""


class PricingProcessor:
    _sleep_seconds = 5
    _cut_off_seconds = 60
    _default_ttl_minutes = 45
    _pay_timeout_seconds = 20
    _lock_pattern = "lock:reprice_trip:{0}"

    def __init__(
        self,
        repositories_obj: Repositories,
        provider_client: ProviderClient,
        redis_client: redis.Client[bytes],
        quotes_stub: transactions_pb2_grpc.QuotationsServiceStub,
        provider_company_id: str,
        quote_ttl: datetime.timedelta | None = None,
    ):
        self._repositories = repositories_obj
        self._provider_client = provider_client
        self._redis_client = redis_client
        self._quotes_stub = quotes_stub
        self._provider_company_id = provider_company_id

        self._quote_ttl = quote_ttl or datetime.timedelta(
            minutes=self._default_ttl_minutes,
        )
        self._logger = stdout.get_logger()

    async def create_quote(self, task: pricing_pb2.CreateQuoteTask) -> None:
        trip = await self._repositories.trips_repository.find_by_offer_id(
            task.quote.offer_id,
        )

        if not trip:
            self._logger.error("Trip not found", offer_id=task.quote.offer_id)

            return

        await self._repositories.quotes_repository.update_status(
            identifier=task.quote.id,
            status=pricing_pb2.Quote.STATUS_PROCESSING,
        )

        with self._provider_client.auth.temporary(task.quote.reseller_id):
            get_boards_response, board_ids = await self._process_trip_boards(
                trip_id=trip.provider_trip_id,
            )

        quote = await self._process_quote(
            quote=task.quote,
            provider_price=_get_price(get_boards_response, frozenset(board_ids)),
            reseller_company_id=task.quote.reseller_company_id,
        )

        await self._repositories.quotes_repository.upsert(quote)

    async def mark_as_failed(self, identifier: str) -> None:
        await self._repositories.quotes_repository.update_status(
            identifier=identifier,
            status=pricing_pb2.Quote.STATUS_FAILED,
        )

    async def _process_quote(
        self,
        quote: pricing_pb2.Quote,
        provider_price: money.Money,
        reseller_company_id: str,
    ) -> pricing_pb2.Quote:
        pay_quote = await self._create_pay_quote(
            request=transactions_pb2.CreateQuotationRequest(
                from_currency=provider_price.currency.code,
                to_currency=quote.reseller_currency,
                amount=provider_price.amount,
                payer_id=reseller_company_id,
                beneficiary_id=self._provider_company_id,
                session_token=string.uuid(),
            ),
        )
        price_proto = pay_quote.amounts.total_amount

        updated_quote = pricing_pb2.Quote()
        updated_quote.CopyFrom(quote)

        updated_quote.pay_quote_id = pay_quote.id
        updated_quote.status = pricing_pb2.Quote.STATUS_COMPLETED
        updated_quote.expires_at.CopyFrom(
            protobuf.datetime_to_protobuf(
                datetime.datetime.now(datetime.UTC) + self._quote_ttl,
            ),
        )
        updated_quote.quoted_offer.CopyFrom(
            pricing_pb2.QuotedOffer(
                price=price_proto,
                price_breakdown=[
                    pricing_pb2.PriceBreakdown(
                        price=price_proto,
                        breakdown_type=pricing_pb2.PriceBreakdown.BREAKDOWN_TYPE_BASE_FARE,
                    ),
                ],
                rules=[],
            ),
        )

        return updated_quote

    async def _create_pay_quote(
        self,
        request: transactions_pb2.CreateQuotationRequest,
    ) -> transaction_models_pb2.Quotation:
        try:
            create_quote_response = await self._quotes_stub.CreateQuotation(
                request=request,
                timeout=self._pay_timeout_seconds,
            )
        except grpc.RpcError as ex:
            raise _PayQuoteCreationFailedError from ex

        return create_quote_response.quotation

    async def _process_trip_boards(
        self,
        trip_id: int,
    ) -> tuple[auto_models.GetTripBoardsResponse, set[int]]:
        trip_boards = await self._provider_client.junction_one_client.get_tripboards(
            trip_id=trip_id,
        )

        boards_to_process = [
            board
            for board in trip_boards.boards
            if not board.status or board.status != auto_models.TripBoardStatus.confirmed
        ]

        trip_boards_response = None

        for board in boards_to_process:
            if not board.id:
                raise ValueError("Missing board id")

            async with self._reprice_lock(trip_id):
                trip_boards_response = await self._reprice_trip_board(
                    trip_id=trip_id,
                    trip_board_id=board.id,
                )

        if not trip_boards_response:
            raise ValueError("No trip board found to process")

        return trip_boards_response, cast(
            set[int],
            {processed_board.id for processed_board in boards_to_process},
        )

    async def _reprice_trip_board(
        self,
        trip_board_id: int,
        trip_id: int,
    ) -> auto_models.GetTripBoardsResponse:
        await self._provider_client.junction_one_client.process_tripboard(
            models.TripboardProcessRequest(
                id=trip_board_id,
                flag=auto_models.TripBoardProcessingFlags.reprice,
            ),
        )

        await asyncio.sleep(self._sleep_seconds)

        async with asyncio.timeout(self._cut_off_seconds):
            while True:
                boards_response = (
                    await self._provider_client.junction_one_client.get_tripboards(
                        trip_id=trip_id,
                    )
                )
                board = next(
                    board_obj
                    for board_obj in boards_response.boards
                    if board_obj.id == trip_board_id
                )

                if board.processing_flags == 0:
                    return boards_response

                if board.exception_flags:
                    raise ValueError("Exception flags are set")

                await asyncio.sleep(self._sleep_seconds)

    def _reprice_lock(self, trip_id: int) -> lock.Lock:
        return self._redis_client.lock(
            name=self._lock_pattern.format(str(trip_id)),
            timeout=self._cut_off_seconds,
        )


class PricingSearchQueue(
    amqp_consumer.AbstractQueue[pricing_pb2.CreateQuoteTask],
):
    def __init__(self, name_prefix: str, processor: PricingProcessor):
        self._name_prefix = name_prefix
        self._processor = processor
        self._logger = stdout.get_logger()

    @property
    def binds(self) -> list[tuple[amqp_types.Exchange, str]]:
        return [
            (amqp_types.Exchange(self._name_prefix), "tasks.pricing"),
        ]

    @property
    def name(self) -> str:
        return "{0}_pricing".format(self._name_prefix)

    async def on_message(
        self,
        msg: amqp_types.Message[pricing_pb2.CreateQuoteTask],
    ) -> None:
        with stdout.context_binding(quote_id=msg.body.quote.id):
            try:
                await self._processor.create_quote(msg.body)
            except errors.JunctionOneError:
                self._logger.exception("J1 reprice failed")
                await self._processor.mark_as_failed(msg.body.quote.id)
            except _PayQuoteCreationFailedError:
                self._logger.exception("Pay quote creation failed")
                await self._processor.mark_as_failed(msg.body.quote.id)
            except ValueError:
                self._logger.exception("Required data not found")
                await self._processor.mark_as_failed(msg.body.quote.id)
