async def test_can_add_a_passenger(  # noqa: WPS218
    mocker: MockerFixture,
    client: httpx.AsyncClient,
    flights_search_repo: FlightSearchResultRepository,
    flights_rocket_trip_repo: RocketTripRepository,
    example_request: Any,
    example_add_passenger: Any,
    example_flight_search_result_one: Any,
) -> None:
    reseller_user_ids = [1001, 1002]
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.create_trip_with_refs",
        return_value=GetTripBoardsResponse(
            trip=Trip(
                id=123,
            ),
        ),
    )
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.create_reseller_user",
        side_effect=[
            UserAccount(id=reseller_user_ids[0]),
            UserAccount(id=reseller_user_ids[1]),
        ],
    )
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.update_reservation",
        return_value=Reservation(),
    )
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.update_passport",
        return_value=User(),
    )
    await flights_search_repo.insert(example_flight_search_result_one)

    response = await client.post(
        "/flights/offers/{0}/passengers".format(OUTBOUND_SEARCH_OFFER_ID),
        json=example_add_passenger,
    )

    assert response.json() == {
        "data": {
            "id": mocker.ANY,
            "links": {"self": mocker.ANY},
            "type": "passengers",
            "attributes": {},
        },
    }
    assert response.status_code == 201

    doc = await flights_rocket_trip_repo.find_by_offer_id(OUTBOUND_SEARCH_OFFER_ID)
    assert doc
    assert len(doc.passenger_ids) == 1
    assert doc.passenger_ids[0].reseller_user_id == reseller_user_ids[0]

    second_passenger = copy.deepcopy(example_add_passenger)
    second_passenger["data"]["attributes"]["email"] = "email2@example.com"

    response = await client.post(
        "/flights/offers/{0}/passengers".format(OUTBOUND_SEARCH_OFFER_ID),
        json=second_passenger,
    )
    assert response.json() == {
        "data": {
            "id": mocker.ANY,
            "links": {"self": mocker.ANY},
            "type": "passengers",
            "attributes": {},
        },
    }
    assert response.status_code == 201

    doc = await flights_rocket_trip_repo.find_by_offer_id(OUTBOUND_SEARCH_OFFER_ID)
    assert doc
    assert len(doc.passenger_ids) == 2
    assert doc.passenger_ids[0].reseller_user_id == reseller_user_ids[0]
    assert doc.passenger_ids[1].reseller_user_id == reseller_user_ids[1]
