async def test_flight_search_round_trip(
    client: httpx.AsyncClient,
    mocker: MockerFixture,
    flights_search_request_repo: FlightSearchRequestRepository,
    flights_search_repo: FlightSearchResultRepository,
    example_request_inbound: Any,
    example_flight_search_result_one: Any,
    example_search_flight_response: SearchFlightsResponse,
) -> None:
    mocker.patch(
        "snowfall.vendor.junction_one.client.JunctionOneClient.search_flights",
        return_value=example_search_flight_response,
    )

    # Outbound insert
    search_object = FlightSearchRequestStorage(
        id=SEARCH_ID,
        reseller_id="RESELLER_ID",
        flight=example_request_inbound["data"]["attributes"],
    )
    await flights_search_request_repo.insert(search_object)

    insert_response = await flights_search_repo.insert(
        example_flight_search_result_one,
    )
    assert insert_response is not None

    # Inbound response
    response = await client.post("/flights/searches", json=example_request_inbound)
    assert response.status_code == 201

    result_id = response.json()["data"]["id"]
    found_result = await flights_search_request_repo.find_by_search_id(result_id)
    assert found_result is not None
    assert result_id == found_result.id

    search_result = await flights_search_repo.find_results_by_search_id(result_id)
    async for result in search_result:
        assert result.id


